// swift-tools-version: 6.0
// The app on the ixOS application runtime (docs/app-model-review.md): the
// Rust core in rust/ embeds forge-app, and ForgeKit owns it for the process,
// reports the lifecycle and runs the event loop. `forge init` points the
// ForgeKit line at a release, or at the checkout when the framework has
// changes since the last release (forge-release.toml).
//
// The screens draw with ForgeUI and keep their alerts and busy buttons as
// ForgeAppKit values (docs/forgeui.md, docs/forgeappkit.md). Both are
// products of the same package; ForgeAppKit brings ForgeUI.

import Foundation
import PackageDescription

// Absolute paths, so linking works whatever directory SwiftPM or Xcode runs the linker from.
let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
// The app's Rust library (rust/), staged by `forge build` / scripts/package-ios-library.sh.
let iosLibSearch = "\(packageDir)/build/ios-device/lib"
// Host (macOS) static library for `swift test`; see scripts/test-swift-host.sh.
let macosLibSearch = "\(packageDir)/build/macos-host/lib"

// The app's Rust library, linked by the targets that make an app of this
// package (the app, its launcher, its tests). Not by the bindings: an app
// that hosts this one (Device Lab) links its own library, which holds this
// app's Rust too.
let rustLibrary: [LinkerSetting] = [
    .linkedLibrary("forge_ffi"),
    // forge-net's HTTPS client verifies certificates with the
    // system trust store (rustls-platform-verifier). A static
    // library does not carry its framework dependencies, so link
    // them here.
    .linkedFramework("Security"),
    .linkedFramework("CoreFoundation"),
    .unsafeFlags(["-L", iosLibSearch], .when(platforms: [.iOS])),
    .unsafeFlags(["-L", macosLibSearch], .when(platforms: [.macOS])),
]

let package = Package(
    name: "Commonplace",
    platforms: [
        .iOS(.v17),
        .macOS(.v14),
    ],
    products: [
        .executable(name: "Commonplace", targets: ["CommonplaceLauncher"]),
        .library(name: "CommonplaceApp", targets: ["CommonplaceApp", "CommonplaceFFI"]),
        // What xtool builds: it expects @main in a library product (see xtool.yml).
        // Named after the app, because it becomes the executable: the process
        // name in the phone's log and the name on its crash reports.
        .library(name: "CommonplaceXtool", targets: ["CommonplaceXtoolApp"]),
    ],
    dependencies: [
        .package(path: "../../forgekit"),
    ],
    targets: [
        // C header + module map generated by UniFFI (scripts/generate-bindings.sh).
        .systemLibrary(
            name: "commonplace_coreFFI",
            path: "Generated/forge_ffiFFI"
        ),
        .target(
            name: "CommonplaceFFI",
            dependencies: ["commonplace_coreFFI", .product(name: "ForgeApp", package: "forgekit")],
            path: "Generated/ForgeFFI",
            // Generated UniFFI code is built in Swift 5 mode; it is not checked for Swift 6 strict concurrency.
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        // SwiftUI views and the view model; they call the Rust API in ForgeFFI.
        .target(
            name: "CommonplaceApp",
            dependencies: [
                "CommonplaceFFI",
                .product(name: "ForgeKit", package: "forgekit"),
                .product(name: "ForgeAppKit", package: "forgekit"),
            ],
            path: "Sources/AppHost"
        ),
        .target(
            name: "CommonplaceXtoolApp",
            dependencies: ["CommonplaceApp"],
            path: "Sources/AppHostXtoolApp",
            linkerSettings: rustLibrary
        ),
        .executableTarget(
            name: "CommonplaceLauncher",
            dependencies: ["CommonplaceApp"],
            path: "Sources/AppHostLauncher",
            linkerSettings: rustLibrary
        ),
        .testTarget(
            name: "AppHostTests",
            dependencies: [
                "CommonplaceApp",
                "CommonplaceFFI",
                .product(name: "ForgeKit", package: "forgekit"),
                .product(name: "ForgeAppKit", package: "forgekit"),
            ],
            path: "Tests/AppHostTests",
            linkerSettings: rustLibrary
        ),
    ]
)
