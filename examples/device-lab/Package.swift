// swift-tools-version: 6.0

import Foundation
import PackageDescription

// Absolute paths, so linking works whatever directory SwiftPM or Xcode runs the linker from.
let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
// The app's Rust library (rust/), staged by `forge build` / scripts/package-ios-library.sh.
let iosLibSearch = "\(packageDir)/build/ios-device/lib"
// Host (macOS) static library for `swift test`; see scripts/test-swift-host.sh.
let macosLibSearch = "\(packageDir)/build/macos-host/lib"

let package = Package(
    name: "DeviceLab",
    platforms: [
        .iOS(.v17),
        .macOS(.v14),
    ],
    products: [
        .executable(name: "DeviceLab", targets: ["AppHostLauncher"]),
        .library(name: "AppHost", targets: ["AppHost"]),
        // What xtool builds: it expects @main in a library product (see xtool.yml).
        .library(name: "AppHostXtool", targets: ["AppHostXtoolApp"]),
    ],
    dependencies: [
        // ForgeKit: Checklist's host (ForgeKit, ForgeApp) and Pocket
        // Library's design system (ForgeUI, ForgeAppKit).
        .package(path: "../../forgekit"),
        // The ForgeUI showcase is an ordinary SwiftUI package, so Device Lab
        // uses it as one.
        .package(path: "../forgeui-showcase"),
    ],
    targets: [
        // C header + module map generated by UniFFI (scripts/generate-bindings.sh).
        .systemLibrary(
            name: "forge_ffiFFI",
            path: "Generated/forge_ffiFFI"
        ),
        // The showcase's other apps: their Rust cores are linked into this
        // app's library (rust/Cargo.toml, rust/embedded/), and each crate's
        // bindings are a Swift module of their own that ForgeFFI re-exports
        // (Generated/ForgeFFI/ForgeFFI+Linked.swift).
        .systemLibrary(name: "weather_coreFFI", path: "Generated/weather_coreFFI"),
        .systemLibrary(name: "checklist_coreFFI", path: "Generated/checklist_coreFFI"),
        .systemLibrary(name: "pocket_library_coreFFI", path: "Generated/pocket_library_coreFFI"),
        .target(
            name: "weather_core",
            dependencies: ["weather_coreFFI", .product(name: "ForgeApp", package: "forgekit")],
            path: "Generated/weather_core",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .target(
            name: "checklist_core",
            dependencies: ["checklist_coreFFI", .product(name: "ForgeApp", package: "forgekit")],
            path: "Generated/checklist_core",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .target(
            name: "pocket_library_core",
            dependencies: ["pocket_library_coreFFI", .product(name: "ForgeApp", package: "forgekit")],
            path: "Generated/pocket_library_core",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .target(
            name: "ForgeFFI",
            dependencies: [
                "forge_ffiFFI", "weather_core", "checklist_core", "pocket_library_core",
                .product(name: "ForgeApp", package: "forgekit"),
            ],
            path: "Generated/ForgeFFI",
            // Generated UniFFI code is built in Swift 5 mode; it is not checked for Swift 6 strict concurrency.
            swiftSettings: [.swiftLanguageMode(.v5)],
            linkerSettings: [
                .linkedLibrary("forge_ffi"),
                // forge-net's HTTPS client verifies certificates with the
                // system trust store (rustls-platform-verifier). A static
                // library does not carry its framework dependencies, so link
                // them here.
                .linkedFramework("Security"),
                .linkedFramework("CoreFoundation"),
                .unsafeFlags(["-L", iosLibSearch], .when(platforms: [.iOS])),
                .unsafeFlags(["-L", macosLibSearch], .when(platforms: [.macOS])),
            ]
        ),
        // The other apps' Swift, from their own folders: each Sources/ entry
        // below is a symlink, so there is one copy of every app.
        .target(name: "WeatherBridge", dependencies: ["ForgeFFI"], path: "Sources/WeatherBridge"),
        .target(name: "WeatherApp", dependencies: ["WeatherBridge"], path: "Sources/WeatherApp"),
        .target(
            name: "ChecklistApp",
            dependencies: ["ForgeFFI", .product(name: "ForgeKit", package: "forgekit")],
            path: "Sources/ChecklistApp",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        // Pocket Library's AppHost, renamed: Device Lab's own target is AppHost.
        .target(
            name: "PocketLibraryApp",
            dependencies: ["ForgeFFI", .product(name: "ForgeAppKit", package: "forgekit")],
            path: "Sources/PocketLibraryApp"
        ),
        // SwiftUI views and the view model; they call the Rust API in ForgeFFI.
        // The Apps screen (AppsView.swift) opens the other apps.
        .target(
            name: "AppHost",
            dependencies: [
                "ForgeFFI", "WeatherApp", "ChecklistApp", "PocketLibraryApp",
                .product(name: "ForgeKit", package: "forgekit"),
                .product(name: "ForgeUIShowcase", package: "forgeui-showcase"),
            ],
            path: "Sources/AppHost"
        ),
        .target(
            name: "AppHostXtoolApp",
            dependencies: ["AppHost"],
            path: "Sources/AppHostXtoolApp"
        ),
        .executableTarget(
            name: "AppHostLauncher",
            dependencies: ["AppHost"],
            path: "Sources/AppHostLauncher"
        ),
        .testTarget(
            name: "AppHostTests",
            dependencies: ["AppHost", "ForgeFFI"],
            path: "Tests/AppHostTests"
        ),
    ]
)
