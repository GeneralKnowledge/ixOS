// swift-tools-version: 6.0

import Foundation
import PackageDescription

// Absolute paths, so linking works whatever directory SwiftPM or Xcode runs the linker from.
let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
// The app's Rust library (rust/), staged by `forge build` / scripts/package-ios-library.sh.
let iosLibSearch = "\(packageDir)/build/ios-device/lib"
// Host (macOS) static library for `swift test`; see scripts/test-swift-host.sh.
let macosLibSearch = "\(packageDir)/build/macos-host/lib"

// Each hosted app's bindings declare the same public View helpers
// (forgeOpenURLs, forgeLaunchAppearance, ...). Without this, Swift sees an
// imported module's extension members in every file of a target, even files
// that don't import it, and calls to them are ambiguous (friction log F19).
// With it, a file sees only the members of the modules it imports.
let hostSettings: [SwiftSetting] = [.enableUpcomingFeature("MemberImportVisibility")]

let package = Package(
    name: "DeviceLab",
    platforms: [
        .iOS(.v17),
        .macOS(.v14),
    ],
    products: [
        .executable(name: "DeviceLab", targets: ["AppHostLauncher"]),
        .library(name: "AppHost", targets: ["AppHost"]),
        // What xtool builds: it expects @main in a library product (see xtool.yml).
        .library(name: "AppHostXtool", targets: ["AppHostXtoolApp"]),
    ],
    dependencies: [
        .package(path: "../../forgekit"),
        // The ForgeUI showcase is an ordinary SwiftUI package, so Device Lab
        // uses it as one.
        .package(path: "../forgeui-showcase"),
        // The other apps on the Apps screen, one small package each (Apps/):
        // the app's own Swift over its own bindings. Their Rust is linked
        // into this app's library (rust/Cargo.toml).
        .package(path: "Apps/Weather"),
        .package(path: "Apps/Checklist"),
        .package(path: "Apps/PocketLibrary"),
        .package(path: "Apps/GoodDog"),
        .package(path: "Apps/Commonplace"),
        .package(path: "Apps/Chat"),
    ],
    targets: [
        // C header + module map generated by UniFFI (scripts/generate-bindings.sh).
        .systemLibrary(
            name: "forge_ffiFFI",
            path: "Generated/forge_ffiFFI"
        ),
        .target(
            name: "ForgeFFI",
            dependencies: [
                "forge_ffiFFI",
                .product(name: "ForgeApp", package: "forgekit"),
            ],
            path: "Generated/ForgeFFI",
            // Generated UniFFI code is built in Swift 5 mode; it is not checked for Swift 6 strict concurrency.
            swiftSettings: [.swiftLanguageMode(.v5)],
            linkerSettings: [
                .linkedLibrary("forge_ffi"),
                // forge-net's HTTPS client verifies certificates with the
                // system trust store (rustls-platform-verifier). A static
                // library does not carry its framework dependencies, so link
                // them here.
                .linkedFramework("Security"),
                .linkedFramework("CoreFoundation"),
                .unsafeFlags(["-L", iosLibSearch], .when(platforms: [.iOS])),
                .unsafeFlags(["-L", macosLibSearch], .when(platforms: [.macOS])),
            ]
        ),
        // SwiftUI views and the view model; they call the Rust API in ForgeFFI.
        // The Apps screen (AppsView.swift) opens the other apps.
        .target(
            name: "AppHost",
            dependencies: [
                "ForgeFFI",
                .product(name: "ForgeKit", package: "forgekit"),
                .product(name: "ForgeUIShowcase", package: "forgeui-showcase"),
                // Every app calls its bindings ForgeFFI and most call their
                // views AppHost, as Device Lab does; the aliases tell them apart.
                // Each app package exports one wrapper target, <App>Embed, so
                // that its modules are dependencies the aliases reach.
                .product(name: "WeatherEmbed", package: "Weather", moduleAliases: ["ForgeFFI": "WeatherFFI"]),
                .product(name: "ChecklistEmbed", package: "Checklist", moduleAliases: ["ForgeFFI": "ChecklistFFI"]),
                .product(
                    name: "PocketLibraryEmbed", package: "PocketLibrary",
                    moduleAliases: ["ForgeFFI": "PocketLibraryFFI", "AppHost": "PocketLibraryApp"]
                ),
                .product(
                    name: "GoodDogEmbed", package: "GoodDog",
                    moduleAliases: ["ForgeFFI": "GoodDogFFI", "AppHost": "GoodDogApp"]
                ),
                .product(
                    name: "CommonplaceEmbed", package: "Commonplace",
                    moduleAliases: ["ForgeFFI": "CommonplaceFFI", "AppHost": "CommonplaceApp"]
                ),
                .product(
                    name: "ChatEmbed", package: "Chat",
                    moduleAliases: ["ForgeFFI": "ChatFFI", "AppHost": "ChatApp"]
                ),
            ],
            path: "Sources/AppHost",
            swiftSettings: hostSettings
        ),
        .target(
            name: "AppHostXtoolApp",
            dependencies: ["AppHost"],
            path: "Sources/AppHostXtoolApp",
            swiftSettings: hostSettings
        ),
        .executableTarget(
            name: "AppHostLauncher",
            dependencies: ["AppHost"],
            path: "Sources/AppHostLauncher",
            swiftSettings: hostSettings
        ),
        .testTarget(
            name: "AppHostTests",
            dependencies: ["AppHost", "ForgeFFI"],
            path: "Tests/AppHostTests"
        ),
    ]
)
