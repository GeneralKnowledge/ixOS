// swift-tools-version: 6.0

import Foundation
import PackageDescription

// Absolute paths, so linking works whatever directory SwiftPM or Xcode runs the linker from.
let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
// The app's Rust library (rust/), staged by `forge build` / scripts/package-ios-library.sh.
let iosLibSearch = "\(packageDir)/build/ios-device/lib"
// Host (macOS) static library for `swift test`; see scripts/test-swift-host.sh.
let macosLibSearch = "\(packageDir)/build/macos-host/lib"

// Each hosted app's bindings declare the same public View helpers
// (forgeOpenURLs, forgeLaunchAppearance, ...). Without this, Swift sees an
// imported module's extension members in every file of a target, even files
// that don't import it, and calls to them are ambiguous (friction log F19).
// With it, a file sees only the members of the modules it imports.
let hostSettings: [SwiftSetting] = [.enableUpcomingFeature("MemberImportVisibility")]

let package = Package(
    name: "DeviceLab",
    platforms: [
        .iOS(.v17),
        .macOS(.v14),
    ],
    products: [
        .executable(name: "DeviceLab", targets: ["AppHostLauncher"]),
        .library(name: "AppHost", targets: ["AppHost"]),
        // What xtool builds: it expects @main in a library product (see xtool.yml).
        .library(name: "AppHostXtool", targets: ["AppHostXtoolApp"]),
    ],
    dependencies: [
        .package(path: "../../forgekit"),
        // The ForgeUI showcase is an ordinary SwiftUI package, so Device Lab
        // uses it as one.
        .package(path: "../forgeui-showcase"),
        // The other apps on the Apps screen: each app's own package, as it
        // builds on its own. Each names its Swift modules after itself
        // (forge.toml [swift]), so nothing clashes. Their Rust is linked into
        // this app's library (rust/Cargo.toml).
        .package(path: "../weather"),
        .package(path: "../checklist"),
        .package(path: "../pocket-library"),
        .package(path: "../good-dog"),
        .package(path: "../commonplace"),
        .package(path: "../fieldkit"),
        .package(path: "../sketchbook"),
        .package(path: "../sums"),
        .package(path: "../soundscape"),
        .package(path: "../urdu-naturally"),
        .package(path: "../relay"),
    ],
    targets: [
        // llama.cpp's prebuilt framework (Metal kernels embedded, nothing to
        // compile on Linux), for running GGUF models such as Ternary-Bonsai
        // Q2_0 in AI Lab. Release b12596; checksum is the zip's SHA-256.
        .binaryTarget(
            name: "llama",
            url: "https://github.com/ggml-org/llama.cpp/releases/download/b12596/llama-b12596-xcframework.zip",
            checksum: "39c2453f1fe1e46c0fc289a3fe41ffb2ad3cb50c1b8c3adfde06e97e0bf8fbd6"
        ),
        // CPython for Python Lab: the official iOS build from python.org,
        // device slice only, laid out by scripts/prepare-python.sh (forge
        // runs it before every iOS build: [ios] prepare in forge.toml). xtool
        // embeds and signs the framework; the standard library goes to the
        // bundle as [ios] resources.
        .binaryTarget(
            name: "Python",
            path: "Generated/Python/Python.xcframework"
        ),
        // A small C API over Python's (include/PythonBridge.h), so Swift
        // never imports Python's headers.
        .target(
            name: "PythonBridge",
            dependencies: ["Python"],
            path: "Sources/PythonBridge"
        ),
        // C header + module map generated by UniFFI (scripts/generate-bindings.sh).
        .systemLibrary(
            name: "forge_ffiFFI",
            path: "Generated/forge_ffiFFI"
        ),
        .target(
            name: "ForgeFFI",
            dependencies: [
                "forge_ffiFFI",
                .product(name: "ForgeApp", package: "forgekit"),
            ],
            path: "Generated/ForgeFFI",
            // Generated UniFFI code is built in Swift 5 mode; it is not checked for Swift 6 strict concurrency.
            swiftSettings: [.swiftLanguageMode(.v5)],
            linkerSettings: [
                .linkedLibrary("forge_ffi"),
                // forge-net's HTTPS client verifies certificates with the
                // system trust store (rustls-platform-verifier). A static
                // library does not carry its framework dependencies, so link
                // them here.
                .linkedFramework("Security"),
                .linkedFramework("CoreFoundation"),
                // Relay's iroh reads network interfaces and DNS settings
                // through SystemConfiguration.
                .linkedFramework("SystemConfiguration"),
                .unsafeFlags(["-L", iosLibSearch], .when(platforms: [.iOS])),
                .unsafeFlags(["-L", macosLibSearch], .when(platforms: [.macOS])),
            ]
        ),
        // SwiftUI views and the view model; they call the Rust API in ForgeFFI.
        // The Apps screen (AppsView.swift) opens the other apps.
        .target(
            name: "AppHost",
            dependencies: [
                "ForgeFFI",
                "llama",
                // Python Lab's interpreter: iPhone only (Python.xcframework
                // has no macOS slice), so host tests build without it.
                .target(name: "PythonBridge", condition: .when(platforms: [.iOS])),
                .product(name: "ForgeKit", package: "forgekit"),
                // Good Dog's native services (the shared forge-native crate).
                .product(name: "ForgeNative", package: "forgekit"),
                .product(name: "ForgeUIShowcase", package: "forgeui-showcase"),
                .product(name: "WeatherApp", package: "weather"),
                .product(name: "ChecklistApp", package: "checklist"),
                .product(name: "PocketLibraryApp", package: "pocket-library"),
                .product(name: "GoodDogApp", package: "good-dog"),
                .product(name: "CommonplaceApp", package: "commonplace"),
                .product(name: "FieldKitApp", package: "fieldkit"),
                .product(name: "SketchbookApp", package: "sketchbook"),
                .product(name: "SumsApp", package: "sums"),
                .product(name: "SoundscapeApp", package: "soundscape"),
                .product(name: "UrduNaturallyApp", package: "urdu-naturally"),
                .product(name: "RelayApp", package: "relay"),
                .product(name: "ForgeUI", package: "forgekit"),
                // The interaction patterns page (PatternsView.swift).
                .product(name: "ForgeAppKit", package: "forgekit"),
            ],
            path: "Sources/AppHost",
            swiftSettings: hostSettings
        ),
        .target(
            name: "AppHostXtoolApp",
            dependencies: ["AppHost"],
            path: "Sources/AppHostXtoolApp",
            swiftSettings: hostSettings
        ),
        .executableTarget(
            name: "AppHostLauncher",
            dependencies: ["AppHost"],
            path: "Sources/AppHostLauncher",
            swiftSettings: hostSettings
        ),
        .testTarget(
            name: "AppHostTests",
            dependencies: ["AppHost", "ForgeFFI"],
            path: "Tests/AppHostTests"
        ),
    ]
)
