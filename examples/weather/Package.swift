// swift-tools-version: 6.0

import Foundation
import PackageDescription

// Absolute paths, so linking works whatever directory SwiftPM or Xcode runs the linker from.
let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
// The app's Rust library (rust/), staged by `forge build` / scripts/package-ios-library.sh.
let iosLibSearch = "\(packageDir)/build/ios-device/lib"
// Host (macOS) static library for `swift test`; see scripts/test-swift-host.sh.
let macosLibSearch = "\(packageDir)/build/macos-host/lib"

// The app's Rust library, linked by the targets that make an app of this
// package (the app, its launcher, its tests). Not by the bindings: an app
// that hosts this one (Device Lab) links its own library, which holds this
// app's Rust too.
let rustLibrary: [LinkerSetting] = [
    .linkedLibrary("forge_ffi"),
    // forge-net's HTTPS client verifies certificates with the
    // system trust store (rustls-platform-verifier). A static
    // library does not carry its framework dependencies, so link
    // them here.
    .linkedFramework("Security"),
    .linkedFramework("CoreFoundation"),
    .unsafeFlags(["-L", iosLibSearch], .when(platforms: [.iOS])),
    .unsafeFlags(["-L", macosLibSearch], .when(platforms: [.macOS])),
]

let package = Package(
    name: "Weather",
    platforms: [
        .iOS(.v17),
        .macOS(.v14),
    ],
    products: [
        .executable(name: "Weather", targets: ["WeatherLauncher"]),
        .library(name: "WeatherApp", targets: ["WeatherApp", "WeatherFFI"]),
        // What xtool builds: it expects @main in a library product (see xtool.yml).
        .library(name: "WeatherXtool", targets: ["WeatherXtoolApp"]),
    ],
    targets: [
        // C header + module map generated by UniFFI (scripts/generate-bindings.sh).
        .systemLibrary(
            name: "weather_coreFFI",
            path: "Generated/forge_ffiFFI"
        ),
        .target(
            name: "WeatherFFI",
            dependencies: ["weather_coreFFI"],
            path: "Generated/ForgeFFI",
            // Generated UniFFI code is built in Swift 5 mode; it is not checked for Swift 6 strict concurrency.
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        // Thin Swift integration layer over the generated bindings: async/await,
        // cancellation, Swift error types, and CoreLocation. Views and view
        // models import this, not ForgeFFI.
        .target(
            name: "WeatherBridge",
            dependencies: ["WeatherFFI"],
            path: "Sources/WeatherBridge"
        ),
        .target(
            name: "WeatherApp",
            dependencies: ["WeatherBridge"],
            path: "Sources/WeatherApp"
        ),
        .target(
            name: "WeatherXtoolApp",
            dependencies: ["WeatherApp"],
            path: "Sources/WeatherXtoolApp",
            linkerSettings: rustLibrary
        ),
        .executableTarget(
            name: "WeatherLauncher",
            dependencies: ["WeatherApp"],
            path: "Sources/WeatherLauncher",
            linkerSettings: rustLibrary
        ),
        .testTarget(
            name: "WeatherAppTests",
            dependencies: ["WeatherApp", "WeatherBridge"],
            path: "Tests/WeatherAppTests",
            linkerSettings: rustLibrary
        ),
    ]
)
