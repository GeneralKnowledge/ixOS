// swift-tools-version: 6.0
// Checklist: the first app on the ixOS application runtime
// (docs/app-model-review.md). ForgeKit owns the Rust core for the process,
// reports the lifecycle and runs the event loop; nothing here is a copy of
// framework code. Inside the checkout ForgeKit comes from ../../forgekit; an
// app outside it uses the release:
//     .package(url: "https://github.com/GeneralKnowledge/ForgeKit.git", exact: "0.3.0")

import Foundation
import PackageDescription

// Absolute paths, so linking works whatever directory SwiftPM runs the linker from.
let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
// The app's Rust library (rust/), staged by `forge build ios`.
let iosLibSearch = "\(packageDir)/build/ios-device/lib"
// Host builds of the same library, for `swift test`: macOS
// (scripts/test-swift-host.sh) and Linux (.github/workflows/app-model.yml).
let macosLibSearch = "\(packageDir)/build/macos-host/lib"
let linuxLibSearch = "\(packageDir)/build/linux-host/lib"

let package = Package(
    name: "Checklist",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [
        .executable(name: "Checklist", targets: ["ChecklistLauncher"]),
        .library(name: "ChecklistApp", targets: ["ChecklistApp"]),
        // What xtool builds: @main in a library product (xtool.yml).
        .library(name: "ChecklistXtool", targets: ["ChecklistXtoolApp"]),
    ],
    dependencies: [
        .package(path: "../../forgekit"),
    ],
    targets: [
        // C header + module map generated by UniFFI (forge bindings generate).
        .systemLibrary(name: "forge_ffiFFI", path: "Generated/forge_ffiFFI"),
        .target(
            name: "ForgeFFI",
            dependencies: ["forge_ffiFFI", .product(name: "ForgeApp", package: "forgekit")],
            path: "Generated/ForgeFFI",
            // Generated UniFFI code is built in Swift 5 mode.
            swiftSettings: [.swiftLanguageMode(.v5)],
            linkerSettings: [
                .linkedLibrary("forge_ffi"),
                .linkedFramework("Security", .when(platforms: [.iOS, .macOS])),
                .linkedFramework("CoreFoundation", .when(platforms: [.iOS, .macOS])),
                .unsafeFlags(["-L", iosLibSearch], .when(platforms: [.iOS])),
                .unsafeFlags(["-L", macosLibSearch], .when(platforms: [.macOS])),
                .unsafeFlags(["-L", linuxLibSearch], .when(platforms: [.linux])),
            ]
        ),
        .target(
            name: "ChecklistApp",
            dependencies: ["ForgeFFI", .product(name: "ForgeKit", package: "forgekit")],
            path: "Sources/ChecklistApp",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .target(
            name: "ChecklistXtoolApp",
            dependencies: ["ChecklistApp", .product(name: "ForgeKit", package: "forgekit")],
            path: "Sources/ChecklistXtoolApp",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .executableTarget(
            name: "ChecklistLauncher",
            dependencies: ["ChecklistApp", .product(name: "ForgeKit", package: "forgekit")],
            path: "Sources/ChecklistLauncher",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .testTarget(
            name: "ChecklistTests",
            dependencies: ["ChecklistApp", "ForgeFFI", .product(name: "ForgeKit", package: "forgekit")],
            path: "Tests/ChecklistTests",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
    ]
)
