    #[test]
    fn adopts_hand_written_files_only_when_nothing_is_lost() {
        let old_plist = "<?xml version=\"1.0\"?>\n<plist version=\"1.0\">\n<dict>\n\t<key>CFBundleDisplayName</key>\n\t<string>Demo</string>\n\t<key>NSLocationWhenInUseUsageDescription</key>\n\t<string>Forecast here.</string>\n</dict>\n</plist>\n";
        let old_yml = "version: 1\nbundleID: org.example.demo\n# comment\nproduct: AppHostXtool\ninfoPath: Info.plist\n";

        // forge.toml lacks the location text: refuse, and say how to fix it.
        let (tmp, c) = app("");
        fs::write(tmp.path().join(INFO_PLIST), old_plist).unwrap();
        fs::write(tmp.path().join(XTOOL_YML), old_yml).unwrap();
        let err = sync(tmp.path(), &c, Mode::Write { force: false }).unwrap_err();
        assert!(err.starts_with("Info.plist in"), "{err}");
        assert!(err.contains("--force"), "{err}");
        assert_eq!(read(tmp.path(), INFO_PLIST), old_plist, "nothing written");

        // Once forge.toml has it, the files are adopted.
        let (_, c) = app("[ios.permissions]\nlocation_when_in_use = \"Forecast here.\"\n");
        sync(tmp.path(), &c, Mode::Write { force: false }).unwrap();
        assert!(read(tmp.path(), INFO_PLIST).contains(MARKER));
        assert!(read(tmp.path(), XTOOL_YML).contains(MARKER));

        // A different xtool product is not silently replaced.
        let (tmp, c) = app("");
        fs::write(
            tmp.path().join(XTOOL_YML),
            old_yml.replace("AppHostXtool", "CounterXtool"),
        )
        .unwrap();
        assert!(sync(tmp.path(), &c, Mode::Write { force: false }).is_err());
        sync(tmp.path(), &c, Mode::Write { force: true }).unwrap();
        assert!(read(tmp.path(), XTOOL_YML).contains("product: AppHostXtool"));
    }

