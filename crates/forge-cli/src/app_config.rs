pub const DEFAULT_XTOOL_PRODUCT: &str = "AppHostXtool";

const MARKER: &str = "Generated by Forge from forge.toml";
const MARKER_LINE: &str = "Generated by Forge from forge.toml. Edit forge.toml, not this file: forge build/run ios and `forge config sync` rewrite it.";

/// `[ios]` in forge.toml.
#[derive(Debug, Clone, Default, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct IosSection {
    /// The SwiftPM library product holding `@main` (xtool's `product`).
    #[serde(default)]
    pub xtool_product: Option<String>,
    /// App icon: a 1024x1024 PNG inside the app (xtool's `iconPath`).
    #[serde(default)]
    pub icon: Option<String>,
    /// portrait, portrait_upside_down, landscape_left, landscape_right.
    #[serde(default)]
    pub orientations: Option<Vec<String>>,
    /// Custom URL schemes the app opens (`myapp://...`).
    #[serde(default)]
    pub url_schemes: Vec<String>,
    /// UIBackgroundModes values, e.g. "remote-notification", "fetch".
    #[serde(default)]
    pub background_modes: Vec<String>,
    /// Permission prompt texts: friendly name (or raw NS…UsageDescription key) → text.
    #[serde(default)]
    pub permissions: BTreeMap<String, String>,
    #[serde(default)]
    pub entitlements: EntitlementsSection,
    #[serde(default)]
    pub signing: SigningSection,
    /// Extra Info.plist keys, written as-is.
    #[serde(default)]
    pub info: toml::Table,
}

#[derive(Debug, Clone, Default, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct EntitlementsSection {
    /// `group.…` identifiers (com.apple.security.application-groups).
    #[serde(default)]
    pub app_groups: Vec<String>,
    /// `applinks:example.com`, `webcredentials:…` (universal links). Paid team.
    #[serde(default)]
    pub associated_domains: Vec<String>,
    /// "development" or "production" (aps-environment). Paid team.
    #[serde(default)]
    pub push_notifications: Option<String>,
    /// "complete", "unless_open" or "until_first_auth".
    #[serde(default)]
    pub data_protection: Option<String>,
    /// Paid team.
    #[serde(default)]
    pub sign_in_with_apple: bool,
    #[serde(default)]
    pub healthkit: bool,
    #[serde(default)]
    pub homekit: bool,
    /// Extra entitlement keys, written as-is.
    #[serde(default)]
    pub extra: toml::Table,
}

#[derive(Debug, Clone, Default, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct SigningSection {
    /// "free" (an Apple ID without the Developer Program) or "paid".
    #[serde(default)]
    pub team_type: Option<String>,
    /// 10-character Apple team ID, for the Xcode project's DEVELOPMENT_TEAM.
    #[serde(default)]
    pub team_id: Option<String>,
}

