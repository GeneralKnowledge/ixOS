    /// The committed examples' generated files match their forge.toml (CI's
    /// guard against editing Info.plist or xtool.yml by hand).
    #[test]
    fn examples_are_in_sync() {
        let examples = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../examples");
        let mut checked = 0;
        for entry in fs::read_dir(&examples).unwrap() {
            let dir = entry.unwrap().path();
            let Ok(toml) = fs::read_to_string(dir.join("forge.toml")) else {
                continue;
            };
            if dir
                .file_name()
                .is_some_and(|n| n.as_encoded_bytes().starts_with(b"."))
            {
                continue;
            }
            let c = ForgeConfig::parse(&toml).unwrap();
            if !c.ios_enabled() {
                continue;
            }
            if let Err(err) = sync(&dir, &c, Mode::Check) {
                panic!("{err}");
            }
            checked += 1;
        }
        assert!(checked >= 3, "expected the iOS examples, found {checked}");
    }

    fn read(dir: &Path, name: &str) -> String {
        fs::read_to_string(dir.join(name)).unwrap()
    }

    fn png_header(w: u32, h: u32, color_type: u8) -> Vec<u8> {
        let mut b = b"\x89PNG\r\n\x1a\n\0\0\0\x0dIHDR".to_vec();
        b.extend_from_slice(&w.to_be_bytes());
        b.extend_from_slice(&h.to_be_bytes());
        b.extend_from_slice(&[8, color_type, 0, 0, 0]);
        b
    }
