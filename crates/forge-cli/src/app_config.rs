//! iOS app configuration: one place (`forge.toml`) for the settings that
//! otherwise live in Info.plist, the entitlements file, xtool.yml,
//! Package.swift and the Xcode project.
//!
//! Forge renders three files in the app directory from `forge.toml` and marks
//! them as generated:
//!
//! - `Info.plist`: display name, version, orientations, permission prompts,
//!   URL schemes, background modes and raw `[ios.info]` keys. xtool merges it
//!   over the Info.plist it builds (`infoPath`); the Xcode project from
//!   `forge init` reads it through `INFOPLIST_FILE`.
//! - `App.entitlements`: app groups, associated domains, push, data
//!   protection, Sign in with Apple and raw `[ios.entitlements.extra]` keys.
//! - `xtool.yml`: bundle ID, the product holding `@main`, and the paths above.
//!
//! It also keeps the `.iOS(...)` platform in Package.swift equal to
//! `minimum_ios`, because xtool takes the deployment target from there.
//!
//! `forge build ios` / `forge run ios` / `forge init` sync these files;
//! `forge config check` fails when they are stale (for CI), and
//! `forge config show` prints the effective settings.

