/// A property-list value.
#[derive(Debug, Clone, PartialEq)]
pub enum Plist {
    String(String),
    Bool(bool),
    Integer(i64),
    Real(f64),
    Array(Vec<Plist>),
    Dict(BTreeMap<String, Plist>),
}

impl Plist {
    fn strings<I: IntoIterator<Item = S>, S: Into<String>>(items: I) -> Self {
        Plist::Array(items.into_iter().map(|s| Plist::String(s.into())).collect())
    }

    fn from_toml(value: &toml::Value, at: &str) -> Result<Self, String> {
        Ok(match value {
            toml::Value::String(s) => Plist::String(s.clone()),
            toml::Value::Boolean(b) => Plist::Bool(*b),
            toml::Value::Integer(i) => Plist::Integer(*i),
            toml::Value::Float(f) => Plist::Real(*f),
            toml::Value::Array(items) => Plist::Array(
                items
                    .iter()
                    .map(|v| Plist::from_toml(v, at))
                    .collect::<Result<_, _>>()?,
            ),
            toml::Value::Table(table) => Plist::Dict(
                table
                    .iter()
                    .map(|(k, v)| Ok((k.clone(), Plist::from_toml(v, &format!("{at}.{k}"))?)))
                    .collect::<Result<_, String>>()?,
            ),
            toml::Value::Datetime(_) => {
                return Err(format!(
                    "{at}: dates are not supported in Info.plist or entitlements values"
                ))
            }
        })
    }

    fn write(&self, out: &mut String, depth: usize) {
        let pad = "\t".repeat(depth);
        match self {
            Plist::String(s) => {
                let _ = writeln!(out, "{pad}<string>{}</string>", xml_escape(s));
            }
            Plist::Bool(true) => {
                let _ = writeln!(out, "{pad}<true/>");
            }
            Plist::Bool(false) => {
                let _ = writeln!(out, "{pad}<false/>");
            }
            Plist::Integer(i) => {
                let _ = writeln!(out, "{pad}<integer>{i}</integer>");
            }
            Plist::Real(f) => {
                let _ = writeln!(out, "{pad}<real>{f}</real>");
            }
            Plist::Array(items) if items.is_empty() => {
                let _ = writeln!(out, "{pad}<array/>");
            }
            Plist::Array(items) => {
                let _ = writeln!(out, "{pad}<array>");
                for item in items {
                    item.write(out, depth + 1);
                }
                let _ = writeln!(out, "{pad}</array>");
            }
            Plist::Dict(map) if map.is_empty() => {
                let _ = writeln!(out, "{pad}<dict/>");
            }
            Plist::Dict(map) => {
                let _ = writeln!(out, "{pad}<dict>");
                for (key, value) in map {
                    let _ = writeln!(out, "{pad}\t<key>{}</key>", xml_escape(key));
                    value.write(out, depth + 1);
                }
                let _ = writeln!(out, "{pad}</dict>");
            }
        }
    }
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn xml_unescape(s: &str) -> String {
    s.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}

fn render_plist(root: &BTreeMap<String, Plist>) -> String {
    let mut out = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n",
    );
    let _ = writeln!(out, "<!-- {MARKER_LINE} -->");
    out.push_str("<plist version=\"1.0\">\n");
    Plist::Dict(root.clone()).write(&mut out, 0);
    out.push_str("</plist>\n");
    out
}

fn ios(cfg: &ForgeConfig) -> std::borrow::Cow<'_, IosSection> {
    match &cfg.ios {
        Some(section) => std::borrow::Cow::Borrowed(section),
        None => std::borrow::Cow::Owned(IosSection::default()),
    }
}

pub fn display_name(cfg: &ForgeConfig) -> &str {
    cfg.app.display_name.as_deref().unwrap_or(&cfg.app.name)
}

pub fn version(cfg: &ForgeConfig) -> &str {
    cfg.app.version.as_deref().unwrap_or("1.0.0")
}

pub fn build_number(cfg: &ForgeConfig) -> &str {
    cfg.app.build_number.as_deref().unwrap_or("1")
}

pub fn xtool_product(cfg: &ForgeConfig) -> String {
    ios(cfg)
        .xtool_product
        .clone()
        .unwrap_or_else(|| DEFAULT_XTOOL_PRODUCT.to_string())
}

fn permission_key(name: &str) -> Option<&str> {
    PERMISSIONS
        .iter()
        .find(|(friendly, _)| *friendly == name)
        .map(|(_, key)| *key)
        .or_else(|| is_raw_usage_key(name).then_some(name))
}

fn is_raw_usage_key(name: &str) -> bool {
    (name.starts_with("NS") || name.starts_with("NFC")) && name.ends_with("UsageDescription")
}

fn lookup<'a>(table: &'a [(&str, &'a str)], name: &str) -> Option<&'a str> {
    table.iter().find(|(k, _)| *k == name).map(|(_, v)| *v)
}

/// The Info.plist keys and values Forge writes.
pub fn info_plist(cfg: &ForgeConfig) -> Result<BTreeMap<String, Plist>, String> {
    let ios = ios(cfg);
    let mut map = BTreeMap::new();
    map.insert(
        "CFBundleDisplayName".into(),
        Plist::String(display_name(cfg).into()),
    );
    map.insert(
        "CFBundleShortVersionString".into(),
        Plist::String(version(cfg).into()),
    );
    map.insert(
        "CFBundleVersion".into(),
        Plist::String(build_number(cfg).into()),
    );
    let orientations = ios
        .orientations
        .clone()
        .unwrap_or_else(|| vec!["portrait".into()]);
    map.insert(
        "UISupportedInterfaceOrientations".into(),
        Plist::strings(
            orientations
                .iter()
                .filter_map(|o| lookup(ORIENTATIONS, o).map(str::to_string)),
        ),
    );
    if !ios.url_schemes.is_empty() {
        let mut url_type = BTreeMap::new();
        url_type.insert(
            "CFBundleURLName".into(),
            Plist::String(cfg.app.bundle_id.clone()),
        );
        url_type.insert(
            "CFBundleURLSchemes".into(),
            Plist::strings(ios.url_schemes.iter().cloned()),
        );
        map.insert(
            "CFBundleURLTypes".into(),
            Plist::Array(vec![Plist::Dict(url_type)]),
        );
    }
    if !ios.background_modes.is_empty() {
        map.insert(
            "UIBackgroundModes".into(),
            Plist::strings(ios.background_modes.iter().cloned()),
        );
    }
    for (name, text) in &ios.permissions {
        if let Some(key) = permission_key(name) {
            map.insert(key.to_string(), Plist::String(text.clone()));
        }
    }
    for (key, value) in &ios.info {
        if map.contains_key(key) {
            return Err(format!(
                "[ios.info] {key} is already set by another forge.toml setting; set it in one place"
            ));
        }
        map.insert(
            key.clone(),
            Plist::from_toml(value, &format!("[ios.info] {key}"))?,
        );
    }
    Ok(map)
}

/// The entitlements Forge writes (empty when the app needs none).
pub fn entitlements(cfg: &ForgeConfig) -> Result<BTreeMap<String, Plist>, String> {
    let ent = &ios(cfg).entitlements;
    let mut map = BTreeMap::new();
    if !ent.app_groups.is_empty() {
        map.insert(
            "com.apple.security.application-groups".into(),
            Plist::strings(ent.app_groups.iter().cloned()),
        );
    }
    if !ent.associated_domains.is_empty() {
        map.insert(
            "com.apple.developer.associated-domains".into(),
            Plist::strings(ent.associated_domains.iter().cloned()),
        );
    }
    if let Some(env) = &ent.push_notifications {
        map.insert("aps-environment".into(), Plist::String(env.clone()));
    }
    if let Some(level) = ent
        .data_protection
        .as_deref()
        .and_then(|l| lookup(DATA_PROTECTION, l))
    {
        map.insert(
            "com.apple.developer.default-data-protection".into(),
            Plist::String(level.into()),
        );
    }
    if ent.sign_in_with_apple {
        map.insert(
            "com.apple.developer.applesignin".into(),
            Plist::strings(["Default"]),
        );
    }
    if ent.healthkit {
        map.insert("com.apple.developer.healthkit".into(), Plist::Bool(true));
    }
    if ent.homekit {
        map.insert("com.apple.developer.homekit".into(), Plist::Bool(true));
    }
    for (key, value) in &ent.extra {
        if map.contains_key(key) {
            return Err(format!(
                "[ios.entitlements.extra] {key} is already set by another [ios.entitlements] setting; set it in one place"
            ));
        }
        map.insert(
            key.clone(),
            Plist::from_toml(value, &format!("[ios.entitlements.extra] {key}"))?,
        );
    }
    Ok(map)
}

fn render_xtool_yml(cfg: &ForgeConfig, has_entitlements: bool) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# {MARKER}. Edit forge.toml, not this file:");
    let _ = writeln!(
        out,
        "# forge build/run ios and `forge config sync` rewrite it."
    );
    let _ = writeln!(out, "version: 1");
    let _ = writeln!(out, "bundleID: {}", cfg.app.bundle_id);
    let _ = writeln!(
        out,
        "# The library product holding the app's @main; xtool names the built app after it."
    );
    let _ = writeln!(out, "product: {}", xtool_product(cfg));
    let _ = writeln!(out, "infoPath: {INFO_PLIST}");
    if has_entitlements {
        let _ = writeln!(out, "entitlementsPath: {ENTITLEMENTS}");
    }
    if let Some(icon) = &ios(cfg).icon {
        let _ = writeln!(out, "iconPath: {icon}");
    }
    out
}

/// One generated file: name, content, and its top-level plist map (plists only).
type RenderedFile = (&'static str, String, Option<BTreeMap<String, Plist>>);

struct Rendered {
    files: Vec<RenderedFile>,
}

fn render(cfg: &ForgeConfig) -> Result<Rendered, String> {
    let info = info_plist(cfg)?;
    let ent = entitlements(cfg)?;
    let has_ent = !ent.is_empty();
    Ok(Rendered {
        files: vec![
            (INFO_PLIST, render_plist(&info), Some(info)),
            // Always written, so the Xcode project's CODE_SIGN_ENTITLEMENTS
            // finds it; xtool.yml only names it when it has entries.
            (ENTITLEMENTS, render_plist(&ent), Some(ent)),
            (XTOOL_YML, render_xtool_yml(cfg, has_ent), None),
        ],
    })
}

fn is_version(s: &str, max_parts: usize) -> bool {
    let parts: Vec<&str> = s.split('.').collect();
    !s.is_empty()
        && parts.len() <= max_parts
        && parts
            .iter()
            .all(|p| !p.is_empty() && p.len() <= 9 && p.chars().all(|c| c.is_ascii_digit()))
}

fn is_url_scheme(s: &str) -> bool {
    s.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '+' | '-' | '.'))
}

fn is_safe_relative_path(p: &str) -> bool {
    let path = Path::new(p);
    !p.is_empty()
        && !path.is_absolute()
        && !path
            .components()
            .any(|c| c == std::path::Component::ParentDir)
        && p.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-' | '/'))
}

fn one_of(table: &[(&str, &str)]) -> String {
    table.iter().map(|(k, _)| *k).collect::<Vec<_>>().join(", ")
}

/// Checks the iOS settings in forge.toml (no file access). Called from
/// `ForgeConfig::validate`, so a bad value fails every command early.
pub fn validate(cfg: &ForgeConfig) -> Result<(), String> {
    if let Some(name) = &cfg.app.display_name {
        if name.trim().is_empty() {
            return Err("app.display_name must not be empty (leave it out to use app.name)".into());
        }
    }
    if let Some(v) = &cfg.app.version {
        if !is_version(v, 3) {
            return Err(format!(
                "app.version = \"{v}\": use one to three numbers separated by dots, such as \"1.2.0\""
            ));
        }
    }
    if let Some(b) = &cfg.app.build_number {
        if !is_version(b, 3) {
            return Err(format!(
                "app.build_number = \"{b}\": use a number such as \"42\" (or up to three dot-separated numbers)"
            ));
        }
    }
    if let Some(min) = &cfg.app.minimum_ios {
        if !is_version(min.trim(), 3) {
            return Err(format!(
                "minimum_ios = \"{min}\": use a version such as \"17.0\""
            ));
        }
    }
    let Some(ios) = &cfg.ios else {
        return Ok(());
    };

    if let Some(product) = &ios.xtool_product {
        if !crate::config::is_valid_project_name(product) {
            return Err(format!(
                "[ios] xtool_product = \"{product}\" is not a SwiftPM product name"
            ));
        }
    }
    if let Some(icon) = &ios.icon {
        if !is_safe_relative_path(icon) || !icon.ends_with(".png") {
            return Err(format!(
                "[ios] icon = \"{icon}\": use a .png path inside the app, such as \"Resources/AppIcon.png\""
            ));
        }
    }
    if let Some(orientations) = &ios.orientations {
        if orientations.is_empty() {
            return Err("[ios] orientations must list at least one orientation".into());
        }
        for o in orientations {
            if lookup(ORIENTATIONS, o).is_none() {
                return Err(format!(
                    "[ios] orientations: unknown \"{o}\" (use {})",
                    one_of(ORIENTATIONS)
                ));
            }
        }
    }
    for scheme in &ios.url_schemes {
        if !is_url_scheme(scheme) {
            return Err(format!(
                "[ios] url_schemes: \"{scheme}\" is not a URL scheme (letters first, then letters, digits, + - .; no \"://\")"
            ));
        }
        if matches!(
            scheme.to_ascii_lowercase().as_str(),
            "http" | "https" | "tel" | "mailto" | "sms" | "file"
        ) {
            return Err(format!(
                "[ios] url_schemes: \"{scheme}\" belongs to the system; use your own scheme, or [ios.entitlements] associated_domains for https links"
            ));
        }
    }
    for mode in &ios.background_modes {
        if !BACKGROUND_MODES.contains(&mode.as_str()) {
            return Err(format!(
                "[ios] background_modes: unknown \"{mode}\" (use {})",
                BACKGROUND_MODES.join(", ")
            ));
        }
    }
    for (name, text) in &ios.permissions {
        if permission_key(name).is_none() {
            return Err(format!(
                "[ios.permissions] unknown permission \"{name}\". Use one of: {}; or a raw Info.plist key ending in UsageDescription",
                one_of(PERMISSIONS)
            ));
        }
        if text.trim().is_empty() {
            return Err(format!(
                "[ios.permissions] {name}: write the sentence iOS shows when it asks the user (App Review rejects empty ones)"
            ));
        }
    }
    let has_permission = |friendly: &str| {
        let key = permission_key(friendly).unwrap_or(friendly);
        ios.permissions
            .keys()
            .any(|n| n == friendly || permission_key(n) == Some(key))
    };
    if has_permission("location_always") && !has_permission("location_when_in_use") {
        return Err("[ios.permissions] location_always also needs location_when_in_use (iOS asks for when-in-use first)".into());
    }
    for (key, _) in &ios.info {
        if let Some((_, instead)) = RESERVED_INFO_KEYS.iter().find(|(k, _)| k == key) {
            return Err(format!(
                "[ios.info] {key} is derived from {instead}; set it there"
            ));
        }
        if is_raw_usage_key(key) {
            return Err(format!(
                "[ios.info] {key}: put permission texts in [ios.permissions]"
            ));
        }
    }

    let ent = &ios.entitlements;
    for group in &ent.app_groups {
        if !group.starts_with("group.") || group.len() <= "group.".len() {
            return Err(format!(
                "[ios.entitlements] app_groups: \"{group}\" must start with \"group.\", such as \"group.{}\"",
                cfg.app.bundle_id
            ));
        }
    }
    for domain in &ent.associated_domains {
        let ok = [
            "applinks:",
            "webcredentials:",
            "activitycontinuation:",
            "appclips:",
        ]
        .iter()
        .any(|p| domain.strip_prefix(p).is_some_and(|host| !host.is_empty()));
        if !ok {
            return Err(format!(
                "[ios.entitlements] associated_domains: \"{domain}\" must look like \"applinks:example.com\" (or webcredentials:, activitycontinuation:, appclips:)"
            ));
        }
    }
    if let Some(env) = &ent.push_notifications {
        if env != "development" && env != "production" {
            return Err(format!(
                "[ios.entitlements] push_notifications = \"{env}\": use \"development\" (debug installs) or \"production\" (TestFlight/App Store)"
            ));
        }
    }
    if let Some(level) = &ent.data_protection {
        if lookup(DATA_PROTECTION, level).is_none() {
            return Err(format!(
                "[ios.entitlements] data_protection = \"{level}\": use {}",
                one_of(DATA_PROTECTION)
            ));
        }
    }

    let signing = &ios.signing;
    if let Some(team) = &signing.team_id {
        if team.len() != 10
            || !team
                .chars()
                .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit())
        {
            return Err(format!(
                "[ios.signing] team_id = \"{team}\": an Apple team ID is 10 capital letters and digits (developer.apple.com → Membership)"
            ));
        }
    }
    match signing.team_type.as_deref() {
        None | Some("paid") => {}
        Some("free") => {
            let ent = entitlements(cfg)?;
            if let Some(what) = paid_entitlements(&ent).first() {
                return Err(format!(
                    "[ios.entitlements] asks for {what}, which Apple only provisions for paid Apple Developer Program teams, but [ios.signing] team_type = \"free\". Remove it, or join the program, sign in to xtool with that team, and set team_type = \"paid\""
                ));
            }
        }
        Some(other) => {
            return Err(format!(
                "[ios.signing] team_type = \"{other}\": use \"free\" (an Apple ID) or \"paid\" (Apple Developer Program)"
            ))
        }
    }
    // Rendering checks [ios.info]/[ios.entitlements.extra] values and clashes.
    info_plist(cfg)?;
    entitlements(cfg)?;
    Ok(())
}

fn paid_entitlements(ent: &BTreeMap<String, Plist>) -> Vec<&'static str> {
    PAID_ONLY_ENTITLEMENTS
        .iter()
        .filter(|(key, _)| ent.contains_key(*key))
        .map(|(_, what)| *what)
        .collect()
}

/// Advice that does not stop a build.
pub fn warnings(cfg: &ForgeConfig, app_dir: &Path) -> Vec<String> {
    let ios = ios(cfg);
    let mut out = Vec::new();
    let ent = entitlements(cfg).unwrap_or_default();
    if ios.signing.team_type.is_none() {
        for what in paid_entitlements(&ent) {
            out.push(format!(
                "{what} needs a paid Apple Developer Program team; signing with a free Apple ID will fail. Set [ios.signing] team_type = \"paid\" once xtool is signed in with such a team"
            ));
        }
    }
    let modes = &ios.background_modes;
    if modes.iter().any(|m| m == "remote-notification") && !ent.contains_key("aps-environment") {
        out.push("background_modes has \"remote-notification\" but [ios.entitlements] push_notifications is not set, so the app will not receive remote pushes".into());
    }
    if modes.iter().any(|m| m == "location")
        && !ios
            .permissions
            .keys()
            .any(|n| permission_key(n) == permission_key("location_always"))
    {
        out.push("background_modes has \"location\"; background location also needs [ios.permissions] location_always".into());
    }
    if modes.iter().any(|m| m == "processing")
        && !ios.info.contains_key("BGTaskSchedulerPermittedIdentifiers")
    {
        out.push("background_modes has \"processing\"; list your task identifiers in [ios.info] BGTaskSchedulerPermittedIdentifiers".into());
    }
    for (service, permission) in selected_services_missing_permissions(cfg, app_dir) {
        out.push(format!(
            "the Rust crate selects the {service} service in native_services!(...), but forge.toml has no [ios.permissions] {permission}; iOS needs that text to ask, so the service will report Unsupported"
        ));
    }
    if let Some(icon) = &ios.icon {
        if let Ok(Some((w, h, alpha))) = png_info(&app_dir.join(icon)) {
            if (w, h) != (1024, 1024) {
                out.push(format!(
                    "[ios] icon {icon} is {w}x{h}; use a 1024x1024 PNG so iOS can scale it for every size"
                ));
            }
            if alpha {
                out.push(format!(
                    "[ios] icon {icon} has an alpha channel; App Store uploads reject icons with transparency"
                ));
            }
        }
    }
    out
}

/// Optional native services whose Swift adapter asks for a permission, and
/// the `[ios.permissions]` name that permission needs. The names are the
/// `ForgeServices+<Name>.swift` adapters in crates/forge-services/swift/optional/.
pub const SERVICE_PERMISSIONS: &[(&str, &str)] = &[
    ("Bluetooth", "bluetooth"),
    ("Location", "location_when_in_use"),
    ("Motion", "motion"),
];

/// Where `scripts/generate-bindings.sh` lists the optional services the app's
/// crate selects.
pub const SELECTED_SERVICES: &str = "Generated/ForgeFFI/ForgeServices+Selected.swift";

/// The optional services listed in the app's generated
/// `ForgeServices+Selected.swift`, or none before bindings are generated.
pub fn selected_services(app_dir: &Path) -> Vec<String> {
    let Ok(text) = fs::read_to_string(app_dir.join(SELECTED_SERVICES)) else {
        return Vec::new();
    };
    text.lines()
        .filter_map(|line| {
            let rest = line.trim_start().strip_prefix("(\"")?;
            let (name, _) = rest.split_once('"')?;
            Some(name.to_string())
        })
        .collect()
}

/// Selected services whose permission text is missing from forge.toml, as
/// (service, permission name) pairs.
fn selected_services_missing_permissions(
    cfg: &ForgeConfig,
    app_dir: &Path,
) -> Vec<(String, &'static str)> {
    let ios = ios(cfg);
    let has = |want: &str| {
        ios.permissions
            .keys()
            .any(|n| permission_key(n) == permission_key(want))
    };
    selected_services(app_dir)
        .into_iter()
        .filter_map(|service| {
            let (_, permission) = SERVICE_PERMISSIONS
                .iter()
                .find(|(name, _)| *name == service)?;
            (!has(permission)).then_some((service, *permission))
        })
        .collect()
}

/// Width, height and whether the PNG has an alpha channel; `None` if the
/// file is not a PNG.
fn png_info(path: &Path) -> std::io::Result<Option<(u32, u32, bool)>> {
    let bytes = fs::read(path)?;
    const SIG: &[u8] = b"\x89PNG\r\n\x1a\n";
    if bytes.len() < 26 || &bytes[..8] != SIG || &bytes[12..16] != b"IHDR" {
        return Ok(None);
    }
    let w = u32::from_be_bytes(bytes[16..20].try_into().unwrap());
    let h = u32::from_be_bytes(bytes[20..24].try_into().unwrap());
    let color_type = bytes[25];
    Ok(Some((w, h, color_type == 4 || color_type == 6)))
}

/// Errors that need files: a missing or non-PNG icon.
fn check_files(cfg: &ForgeConfig, app_dir: &Path) -> Result<(), String> {
    if let Some(icon) = &ios(cfg).icon {
        let path = app_dir.join(icon);
        match png_info(&path) {
            Ok(Some(_)) => {}
            Ok(None) => return Err(format!("[ios] icon {icon} is not a PNG file")),
            Err(e) => {
                return Err(format!(
                    "[ios] icon {icon}: cannot read {}: {e}",
                    path.display()
                ))
            }
        }
    }
    Ok(())
}

/// `<key>K</key><string>V</string>` pairs of a hand-written plist, or `None`
/// if it has any value that is not a plain string.
fn plain_string_pairs(content: &str) -> Option<Vec<(String, String)>> {
    let mut pairs = Vec::new();
    let mut rest = content;
    while let Some(start) = rest.find("<key>") {
        rest = &rest[start + 5..];
        let end = rest.find("</key>")?;
        let key = xml_unescape(&rest[..end]);
        rest = rest[end + 6..].trim_start();
        let value = rest.strip_prefix("<string>")?;
        let end = value.find("</string>")?;
        pairs.push((key, xml_unescape(&value[..end])));
        rest = &value[end + 9..];
    }
    Some(pairs)
}

/// Whether replacing a file Forge did not write loses nothing: every setting
/// in it is also in what Forge would write. Apps made before Forge generated
/// these files (and the examples) pass this when forge.toml has their settings.
fn adoptable(file: &str, old: &str, new: &str, new_map: Option<&BTreeMap<String, Plist>>) -> bool {
    match new_map {
        Some(map) => plain_string_pairs(old).is_some_and(|pairs| {
            pairs
                .iter()
                .all(|(k, v)| map.get(k) == Some(&Plist::String(v.clone())))
        }),
        None => {
            debug_assert_eq!(file, XTOOL_YML);
            let new_lines: Vec<&str> = new.lines().map(str::trim).collect();
            old.lines()
                .map(str::trim)
                .filter(|l| !l.is_empty() && !l.starts_with('#'))
                .all(|l| new_lines.contains(&l))
        }
    }
}

/// The `.iOS(...)` platform in Package.swift, as written and normalised.
fn package_ios_platform(package: &str) -> Result<Option<(String, String)>, String> {
    let found: Vec<usize> = package.match_indices(".iOS(").map(|(i, _)| i).collect();
    match found.as_slice() {
        [] => Ok(None),
        [at] => {
            let start = at + ".iOS(".len();
            let end = package[start..]
                .find(')')
                .ok_or("Package.swift: unclosed .iOS(")?
                + start;
            let inner = package[start..end].trim();
            let version = if let Some(v) = inner.strip_prefix(".v") {
                v.replace('_', ".")
            } else if inner.len() >= 2 && inner.starts_with('"') && inner.ends_with('"') {
                inner[1..inner.len() - 1].to_string()
            } else {
                return Err(format!(
                    "Package.swift: cannot read the iOS version in .iOS({inner})"
                ));
            };
            Ok(Some((package[*at..=end].to_string(), normalise_version(&version))))
        }
        _ => Err("Package.swift declares .iOS(...) more than once; keep one platform entry so Forge can match it to minimum_ios".into()),
    }
}

fn normalise_version(v: &str) -> String {
    let mut parts: Vec<&str> = v.trim().split('.').collect();
    while parts.len() > 2 && parts.last() == Some(&"0") {
        parts.pop();
    }
    if parts.len() == 1 {
        parts.push("0");
    }
    parts.join(".")
}

/// What `sync` does with files that differ from forge.toml.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    /// Rewrite them. `force` also replaces hand-written files that hold
    /// settings forge.toml does not have.
    Write { force: bool },
    /// Change nothing; fail if any is stale (for CI).
    Check,
}

#[derive(Debug, Default)]
pub struct Outcome {
    /// Files written (Write) or stale (Check), relative to the app.
    pub changed: Vec<String>,
    pub warnings: Vec<String>,
}

/// Brings Info.plist, App.entitlements, xtool.yml and Package.swift's iOS
/// platform in line with forge.toml. Does nothing for apps without iOS.
pub fn sync(app_dir: &Path, cfg: &ForgeConfig, mode: Mode) -> Result<Outcome, String> {
    let mut outcome = Outcome::default();
    if !cfg.ios_enabled() {
        return Ok(outcome);
    }
    check_files(cfg, app_dir)?;
    let rendered = render(cfg)?;
    let mut writes: Vec<(PathBuf, String)> = Vec::new();
    let mut blocked: Vec<String> = Vec::new();
    for (name, content, map) in &rendered.files {
        let path = app_dir.join(name);
        let old = match fs::read_to_string(&path) {
            Ok(old) => Some(old),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
            Err(e) => return Err(format!("cannot read {}: {e}", path.display())),
        };
        match old {
            Some(old) if old == *content => continue,
            Some(old)
                if !old.contains(MARKER)
                    && !adoptable(name, &old, content, map.as_ref())
                    && mode != (Mode::Write { force: true }) =>
            {
                blocked.push(name.to_string());
            }
            _ => writes.push((path, content.clone())),
        }
    }
    if !blocked.is_empty() {
        return Err(format!(
            "{} in {} {} settings that forge.toml does not have, and Forge now generates {} from forge.toml. Move those settings into forge.toml (docs/app-config.md: [ios.permissions], [ios.info], [ios.entitlements], [ios] xtool_product), then run `forge config sync`; or run `forge config sync --force` to replace {} and drop them",
            blocked.join(" and "),
            app_dir.display(),
            if blocked.len() == 1 { "has" } else { "have" },
            if blocked.len() == 1 { "it" } else { "them" },
            if blocked.len() == 1 { "it" } else { "them" },
        ));
    }

    // xtool takes the deployment target from Package.swift's platforms.
    let package_path = app_dir.join("Package.swift");
    if let (Some(min), Ok(package)) = (&cfg.app.minimum_ios, fs::read_to_string(&package_path)) {
        let want = normalise_version(min);
        match package_ios_platform(&package)? {
            Some((written, have)) if have != want => {
                let replacement = format!(".iOS(\"{want}\")");
                writes.push((package_path, package.replacen(&written, &replacement, 1)));
            }
            Some(_) => {}
            None => outcome.warnings.push(format!(
                "Package.swift has no .iOS(...) platform; add .iOS(\"{want}\") to platforms so xtool builds for minimum_ios"
            )),
        }
    }

    outcome.changed = writes
        .iter()
        .map(|(p, _)| {
            p.strip_prefix(app_dir)
                .unwrap_or(p)
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    match mode {
        Mode::Check if !outcome.changed.is_empty() => {
            return Err(format!(
                "{} {} out of date with forge.toml in {}; run `forge config sync --project {}`",
                outcome.changed.join(", "),
                if outcome.changed.len() == 1 {
                    "is"
                } else {
                    "are"
                },
                app_dir.display(),
                app_dir.display()
            ));
        }
        Mode::Check => {}
        Mode::Write { .. } => {
            for (path, content) in &writes {
                fs::write(path, content)
                    .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
            }
        }
    }
    outcome.warnings.extend(warnings(cfg, app_dir));
    Ok(outcome)
}

/// Settings in the app's Xcode project (the optional macOS path) that differ
/// from forge.toml. Xcode keeps bundle ID, deployment target and team in its
/// own build settings, so Forge reports these rather than editing the project.
pub fn xcode_differences(cfg: &ForgeConfig, app_dir: &Path) -> Vec<String> {
    let Some(pbxproj) = fs::read_dir(app_dir.join("Xcode")).ok().and_then(|dir| {
        dir.filter_map(Result::ok)
            .map(|e| e.path())
            .find(|p| p.extension().is_some_and(|e| e == "xcodeproj"))
            .map(|p| p.join("project.pbxproj"))
    }) else {
        return Vec::new();
    };
    let Ok(project) = fs::read_to_string(&pbxproj) else {
        return Vec::new();
    };
    let values = |setting: &str| -> Vec<String> {
        let needle = format!("{setting} = ");
        let mut found: Vec<String> = project
            .lines()
            .filter_map(|l| l.trim().strip_prefix(&needle))
            .map(|v| v.trim_end_matches(';').trim_matches('"').to_string())
            .collect();
        found.sort();
        found.dedup();
        found
    };
    let rel = pbxproj
        .strip_prefix(app_dir)
        .unwrap_or(&pbxproj)
        .display()
        .to_string();
    let mut out = Vec::new();
    let bundle_ids = values("PRODUCT_BUNDLE_IDENTIFIER");
    if !bundle_ids.is_empty() && !bundle_ids.contains(&cfg.app.bundle_id) {
        out.push(format!(
            "{rel}: PRODUCT_BUNDLE_IDENTIFIER is {} but forge.toml bundle_id is {}",
            bundle_ids.join(", "),
            cfg.app.bundle_id
        ));
    }
    if let Some(min) = &cfg.app.minimum_ios {
        let want = normalise_version(min);
        for have in values("IPHONEOS_DEPLOYMENT_TARGET") {
            if normalise_version(&have) != want {
                out.push(format!(
                    "{rel}: IPHONEOS_DEPLOYMENT_TARGET is {have} but forge.toml minimum_ios is {want}"
                ));
            }
        }
    }
    if let Some(team) = &ios(cfg).signing.team_id {
        let teams = values("DEVELOPMENT_TEAM");
        if !teams.contains(team) {
            out.push(format!(
                "{rel}: DEVELOPMENT_TEAM is {} but forge.toml team_id is {team} (set it under Signing & Capabilities)",
                if teams.iter().all(String::is_empty) { "unset".to_string() } else { teams.join(", ") }
            ));
        }
    }
    if !project
        .lines()
        .any(|l| l.trim_start().starts_with("INFOPLIST_FILE = "))
    {
        out.push(format!(
            "{rel} does not read the generated Info.plist; Xcode builds miss forge.toml's permissions and URL schemes (add INFOPLIST_FILE = ../Info.plist and CODE_SIGN_ENTITLEMENTS = ../App.entitlements, as apps from forge init have)"
        ));
    }
    out
}

/// A readable summary of the effective iOS configuration.
pub fn summary(cfg: &ForgeConfig) -> Result<String, String> {
    let ios = ios(cfg);
    let mut out = String::new();
    let _ = writeln!(out, "App:            {}", cfg.app.name);
    let _ = writeln!(out, "Bundle ID:      {}", cfg.app.bundle_id);
    let _ = writeln!(out, "Display name:   {}", display_name(cfg));
    let _ = writeln!(
        out,
        "Version:        {} (build {})",
        version(cfg),
        build_number(cfg)
    );
    let _ = writeln!(
        out,
        "Minimum iOS:    {}",
        cfg.app.minimum_ios.as_deref().unwrap_or("-")
    );
    let _ = writeln!(out, "xtool product:  {}", xtool_product(cfg));
    let _ = writeln!(
        out,
        "Icon:           {}",
        ios.icon
            .as_deref()
            .unwrap_or("none (iOS shows a blank icon)")
    );
    let _ = writeln!(
        out,
        "Signing:        team type {}, team ID {}",
        ios.signing.team_type.as_deref().unwrap_or("not set"),
        ios.signing.team_id.as_deref().unwrap_or("not set")
    );
    let info = info_plist(cfg)?;
    let _ = writeln!(out, "\n{INFO_PLIST}:");
    for (k, v) in &info {
        let _ = writeln!(out, "  {k} = {}", short(v));
    }
    let ent = entitlements(cfg)?;
    let _ = writeln!(out, "\n{ENTITLEMENTS}:");
    if ent.is_empty() {
        let _ = writeln!(out, "  (none)");
    }
    for (k, v) in &ent {
        let _ = writeln!(out, "  {k} = {}", short(v));
    }
    Ok(out)
}

fn short(v: &Plist) -> String {
    match v {
        Plist::String(s) => format!("{s:?}"),
        Plist::Bool(b) => b.to_string(),
        Plist::Integer(i) => i.to_string(),
        Plist::Real(f) => f.to_string(),
        Plist::Array(items) => format!(
            "[{}]",
            items.iter().map(short).collect::<Vec<_>>().join(", ")
        ),
        Plist::Dict(map) => format!(
            "{{{}}}",
            map.iter()
                .map(|(k, v)| format!("{k}: {}", short(v)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

