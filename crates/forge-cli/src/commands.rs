use std::fs;
use std::path::{Path, PathBuf};

use crate::config::{self, ForgeConfig};
use crate::runner::CommandRunner;

const PLACEHOLDER_PACKAGE: &str = "FORGE_PACKAGE_NAME";
const PLACEHOLDER_APP_NAME: &str = "FORGE_APP_NAME";
const PLACEHOLDER_BUNDLE: &str = "FORGE_BUNDLE_ID";
const PLACEHOLDER_SUPPORT_DIR: &str = "FORGE_APP_SUPPORT_DIR";

/// Absolute path to an app package directory (SwiftPM + forge.toml).
pub fn resolve_project_dir(project: &Path) -> PathBuf {
    let root = workspace_root();
    if project.is_absolute() {
        project.to_path_buf()
    } else {
        root.join(project)
    }
}

pub fn generated_dir_for_project(project: &Path) -> PathBuf {
    resolve_project_dir(project).join("Generated")
}

fn generated_dir_arg(root: &Path, generated: &Path) -> String {
    match generated.strip_prefix(root) {
        Ok(rel) => rel.to_string_lossy().into_owned(),
        Err(_) => generated.to_string_lossy().into_owned(),
    }
}

pub fn workspace_root() -> PathBuf {
    if let Ok(dir) = std::env::var("FORGE_WORKSPACE") {
        return PathBuf::from(dir);
    }
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .unwrap_or_else(|_| PathBuf::from("."))
}

fn run_checked(
    runner: &dyn CommandRunner,
    program: &str,
    args: &[&str],
    cwd: Option<&Path>,
) -> Result<(), String> {
    let output = runner.run(program, args, cwd)?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        let stdout = String::from_utf8_lossy(&output.stdout);
        return Err(format!(
            "{program} exited with {}:\n{stdout}{stderr}",
            output.status
        ));
    }
    Ok(())
}

pub fn doctor(runner: &dyn CommandRunner) -> Result<(), String> {
    let root = workspace_root();
    let script = root.join("scripts/validate-toolchain.sh");
    if script.exists() {
        run_checked(runner, "bash", &[script.to_str().unwrap()], Some(&root))?;
    } else {
        println!("Forge workspace root: {}", root.display());
        let _ = try_version(runner, "rustc", &["--version"]);
        let _ = try_version(runner, "cargo", &["--version"]);
        let _ = try_version(runner, "swift", &["--version"]);
        let _ = try_version(runner, "xtool", &["--version"]);
    }
    Ok(())
}

fn try_version(runner: &dyn CommandRunner, program: &str, args: &[&str]) -> Result<(), String> {
    match runner.run(program, args, None) {
        Ok(out) if out.status.success() => {
            print!("{}", String::from_utf8_lossy(&out.stdout));
            Ok(())
        }
        Ok(out) => Err(String::from_utf8_lossy(&out.stderr).into()),
        Err(e) => {
            println!("{program}: not available ({e})");
            Ok(())
        }
    }
}

pub fn init(name: &str, bundle_id: &str) -> Result<(), String> {
    if !config::is_valid_project_name(name) {
        return Err(
            "invalid project name: use ASCII letters, digits, hyphen, underscore; must start with a letter".into(),
        );
    }
    let probe = format!(
        r#"
[app]
name = "{name}"
bundle_id = "{bundle_id}"
minimum_ios = "17.0"
[rust]
core_crate = "forge-core"
ffi_crate = "forge-ffi"
[build]
ios_device = true
ios_simulator = false
"#,
    );
    ForgeConfig::parse(&probe)?;

    let root = workspace_root();
    let dest = root.join("examples").join(name);
    if dest.exists() {
        return Err(format!("destination already exists: {}", dest.display()));
    }

    let template = root.join("templates/ios-app");
    if !template.is_dir() {
        return Err("template missing at templates/ios-app".into());
    }
    validate_template(&template)?;

    copy_template(&template, &dest)?;
    substitute_placeholders(&dest, name, bundle_id)?;

    let generated = dest.join("Generated");
    fs::create_dir_all(&generated).map_err(|e| e.to_string())?;

    let runner = crate::runner::RealRunner;
    bindings_generate(&runner, &generated)?;

    println!("Created Forge app at {}", dest.display());
    println!("Note: iOS apps generated by forge init are workspace-local in v0.1.");
    println!(
        "Build Rust FFI from repo root, then: cd {} && xtool dev",
        dest.display()
    );
    Ok(())
}

fn validate_template(template: &Path) -> Result<(), String> {
    for rel in [
        "Package.swift",
        "forge.toml",
        "xtool.yml",
        "Sources/AppHost/App.swift",
    ] {
        let p = template.join(rel);
        if !p.is_file() {
            return Err(format!("incomplete template: missing {}", rel));
        }
    }
    Ok(())
}

fn copy_template(src: &Path, dst: &Path) -> Result<(), String> {
    fs::create_dir_all(dst).map_err(|e| e.to_string())?;
    for entry in fs::read_dir(src).map_err(|e| e.to_string())? {
        let entry = entry.map_err(|e| e.to_string())?;
        let name = entry.file_name();
        if name == "Generated" {
            continue;
        }
        let ty = entry.file_type().map_err(|e| e.to_string())?;
        let target = dst.join(name);
        if ty.is_dir() {
            copy_template(&entry.path(), &target)?;
        } else {
            fs::copy(entry.path(), &target).map_err(|e| e.to_string())?;
        }
    }
    Ok(())
}

fn substitute_placeholders(dest: &Path, name: &str, bundle_id: &str) -> Result<(), String> {
    let support_dir = name;
    walk_substitute(dest, name, bundle_id, support_dir)
}

fn walk_substitute(
    dir: &Path,
    package_name: &str,
    bundle_id: &str,
    support_dir: &str,
) -> Result<(), String> {
    for entry in fs::read_dir(dir).map_err(|e| e.to_string())? {
        let entry = entry.map_err(|e| e.to_string())?;
        let path = entry.path();
        if path.file_name().is_some_and(|n| n == "Generated") {
            continue;
        }
        if entry.file_type().map_err(|e| e.to_string())?.is_dir() {
            walk_substitute(&path, package_name, bundle_id, support_dir)?;
        } else if is_text_template(&path) {
            let content = fs::read_to_string(&path).map_err(|e| e.to_string())?;
            let updated = content
                .replace(PLACEHOLDER_PACKAGE, package_name)
                .replace(PLACEHOLDER_APP_NAME, package_name)
                .replace(PLACEHOLDER_BUNDLE, bundle_id)
                .replace(PLACEHOLDER_SUPPORT_DIR, support_dir);
            fs::write(&path, updated).map_err(|e| e.to_string())?;
        }
    }
    Ok(())
}

fn is_text_template(path: &Path) -> bool {
    matches!(
        path.extension().and_then(|e| e.to_str()),
        Some("swift" | "toml" | "yml" | "yaml" | "md")
    ) || path.file_name().is_some_and(|n| n == "Package.swift")
}

pub fn test(runner: &dyn CommandRunner, _project: Option<&Path>) -> Result<(), String> {
    let root = workspace_root();
    run_checked(runner, "cargo", &["test", "--workspace"], Some(&root))?;
    run_checked(
        runner,
        "cargo",
        &["fmt", "--all", "--", "--check"],
        Some(&root),
    )?;
    Ok(())
}

pub fn bindings_generate(runner: &dyn CommandRunner, out: &Path) -> Result<(), String> {
    let root = workspace_root();
    let script = root.join("scripts/generate-bindings.sh");
    let out_str = out.to_str().ok_or("invalid output path")?;
    run_checked(
        runner,
        "bash",
        &[script.to_str().unwrap(), out_str],
        Some(&root),
    )
}

pub fn build_ios(runner: &dyn CommandRunner, project: &Path) -> Result<(), String> {
    let root = workspace_root();
    let project_dir = resolve_project_dir(project);
    let forge_toml = project_dir.join("forge.toml");
    if forge_toml.exists() {
        let content = fs::read_to_string(&forge_toml).map_err(|e| e.to_string())?;
        ForgeConfig::parse(&content)?;
    }

    let generated = generated_dir_for_project(project);
    let generated_arg = generated_dir_arg(&root, &generated);
    let package_script = root.join("scripts/package-ios-library.sh");

    run_checked(
        runner,
        "bash",
        &[
            package_script.to_str().unwrap(),
            generated_arg.as_str(),
        ],
        Some(&root),
    )?;

    if which_xtool(runner)? {
        run_checked(runner, "xtool", &["dev"], Some(&project_dir))?;
    } else {
        return Err(
            "xtool not available: Rust library packaged, but iOS app build requires xtool + Darwin SDK (see docs/linux-setup.md)".into(),
        );
    }
    Ok(())
}

pub fn devices(runner: &dyn CommandRunner) -> Result<(), String> {
    if !which_xtool(runner)? {
        return Err("xtool not installed".into());
    }
    let output = runner.run("xtool", &["devices"], None)?;
    print!("{}", String::from_utf8_lossy(&output.stdout));
    if !output.status.success() {
        return Err(String::from_utf8_lossy(&output.stderr).into());
    }
    Ok(())
}

pub fn install_ios(runner: &dyn CommandRunner, ipa: &Path) -> Result<(), String> {
    if !which_xtool(runner)? {
        return Err("xtool not installed".into());
    }
    let ipa_str = ipa.to_str().ok_or("invalid ipa path")?;
    run_checked(runner, "xtool", &["install", ipa_str], None)
}

pub fn run_ios(runner: &dyn CommandRunner, project: &Path) -> Result<(), String> {
    build_ios(runner, project)
}

fn which_xtool(runner: &dyn CommandRunner) -> Result<bool, String> {
    match runner.run("xtool", &["--version"], None) {
        Ok(o) if o.status.success() => Ok(true),
        Ok(_) => Ok(false),
        Err(_) => Ok(false),
    }
}

#[cfg(test)]
mod init_tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn generated_dir_for_counter_example() {
        let root = workspace_root();
        let gen = generated_dir_for_project(Path::new("examples/counter"));
        assert_eq!(gen, root.join("examples/counter/Generated"));
    }

    #[test]
    fn init_substitutes_placeholders_and_generates_bindings() {
        let root = workspace_root();
        let name = "InitTestApp";
        let dest = root.join("examples").join(name);
        let _ = fs::remove_dir_all(&dest);
        init(name, "org.example.inittest").expect("init");
        let pkg = fs::read_to_string(dest.join("Package.swift")).unwrap();
        assert!(pkg.contains("name: \"InitTestApp\""));
        assert!(!pkg.contains("FORGE_PACKAGE_NAME"));
        assert!(dest.join("Generated/forge_ffi.swift").is_file());
        let vm = fs::read_to_string(dest.join("Sources/AppHost/CounterViewModel.swift")).unwrap();
        assert!(vm.contains("InitTestApp"));
        fs::remove_dir_all(dest).unwrap();
    }

    #[test]
    fn init_fails_when_destination_exists() {
        let root = workspace_root();
        let dest = root.join("examples").join("counter");
        let err = init("counter", "org.example.counter").unwrap_err();
        assert!(err.contains("already exists"));
        assert!(dest.exists());
    }
}
